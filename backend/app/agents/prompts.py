TRIAGE_USER_TEMPLATE = "用户消息：{message}\n\n请只输出意图标签（寒暄/求助/倾诉/咨询/危机）："


# 回复骨架按 triage_intent 分支（2026-09-08 实测「什么是焦虑」被分类为咨询后仍被
# 套倾诉骨架，产出"接情绪+闭合问句"的答非所问缝合怪，且空历史下幻觉归因「最近
# 你说过…」）：咨询=先直接回答问题；倾诉/其他=先接情绪
REPLY_SKELETON_DEFAULT = (
    "回复骨架：先接住情绪（一句即可）→ 给出一个能立刻尝试的具体做法"
    "（优先取自上面与话题相关的片段，用你自己的话）→ 以开放式问题收尾。"
)
REPLY_SKELETON_CONSULT = (
    "回复骨架：先用通俗语言直接回答用户问的问题（可结合上面与话题相关的知识库"
    "片段，用你自己的话讲，不堆砌专业术语）。若用户问的是「怎么缓解/改善/应对/"
    "怎么办」类求做法问题，须从知识库片段中给出 2-3 种彼此不同的具体做法（如呼吸"
    "放松、睡眠卫生、任务拆解），不要只给一种，也不要重复同一种做法的不同说法。"
    "→ 再自然衔接到用户的处境或感受（一句即可，对话历史里没有相关内容就不要说"
    "「你说过…」）→ 以开放式问题收尾。"
)


def get_reply_skeleton(triage_intent: str) -> str:
    """按意图取回复骨架：咨询=先答问，其余=先接情绪。"""
    return REPLY_SKELETON_CONSULT if triage_intent == "咨询" else REPLY_SKELETON_DEFAULT


